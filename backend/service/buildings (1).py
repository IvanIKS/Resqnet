# ----------------------------------------------------------------------
FLOOR_HEIGHT_M = 3.0          # середня висота одного поверху, м
REFUGE_MIN_HEIGHT_M = 9.0     # мінімальна висота будівлі (~3 поверхи), м
ROOF_M2_PER_PERSON = 1.5      # лише для довідкової оцінки місткості (на відбір не впливає)
REQUIRE_FLAT_ROOF = False     # True = лише плоскі дахи (якщо є атрибут roof_shape)
RISKY_CLASS = None            # None = у т.ч. зона сильного пошкодження вважається придатною;
                              # "Сильне" = у цій зоні укриття позначаються як ризиковані (підмив)

REFUGE_OK = "Придатне"
REFUGE_RISKY = "Ризиковане (зона підмиву)"


def add_height_and_refuge(b):
    """Додає: height_final_m, height_source, floors_est, is_refuge, refuge_status, roof_capacity."""
    b = b.copy()

    h = pd.to_numeric(b["height"], errors="coerce") if "height" in b.columns \
        else pd.Series(np.nan, index=b.index)
    fl = pd.to_numeric(b["num_floors"], errors="coerce") if "num_floors" in b.columns \
        else pd.Series(np.nan, index=b.index)
    h = h.where(h > 0)
    fl = fl.where(fl > 0)

    from_floors = fl * FLOOR_HEIGHT_M
    b["height_final_m"] = h.fillna(from_floors).round(1)
    b["height_source"] = np.where(h.notna(), "height",
                          np.where(fl.notna(), f"num_floors×{FLOOR_HEIGHT_M:g} м", "немає даних"))
    b["floors_est"] = fl.fillna((h / FLOOR_HEIGHT_M).round()).astype("float")

    ok = b["height_final_m"] >= REFUGE_MIN_HEIGHT_M
    if REQUIRE_FLAT_ROOF and "roof_shape" in b.columns:
        ok &= b["roof_shape"].astype(str).str.lower().eq("flat")

    b["is_refuge"] = ok
    risky = (b["damage_class"] == RISKY_CLASS) if RISKY_CLASS else pd.Series(False, index=b.index)
    b["refuge_status"] = np.where(ok, np.where(risky, REFUGE_RISKY, REFUGE_OK), "—")
    b["roof_capacity_people"] = np.where(ok, (b["area_m2"] / ROOF_M2_PER_PERSON).astype(int), 0)
    return b

