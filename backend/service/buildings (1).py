NO_DAMAGE = "Без пошкоджень"


def build_damage_rings(flood_gdf, zones=ZONES):
    """Кільцеві буфери від межі затоплення (без самої затопленої території)."""
    flood = flood_gdf.geometry.iloc[0]
    rings = []
    for z in zones:
        outer = flood.buffer(z["d_max"])
        inner = flood if z["d_min"] == 0 else flood.buffer(z["d_min"])
        rings.append({**z, "geometry": outer.difference(inner)})
    return gpd.GeoDataFrame(rings, geometry="geometry", crs=flood_gdf.crs)


def classify_buildings(buildings, flood_gdf, zones=ZONES):
    """Додає: dist_to_flood_m, damage_class, damage_pct_*, damage_area_*_m2, damaged_zone."""
    b = buildings.copy()
    flood = flood_gdf.geometry.iloc[0]
    b["dist_to_flood_m"] = b.geometry.distance(flood).round(1)      # 0 якщо перетинає

    edges = [-1e-6] + [z["d_max"] for z in zones]                   # перший клас включає 0
    labels = [z["name"] for z in zones]
    cls = pd.cut(b["dist_to_flood_m"], bins=edges, labels=labels, right=True)
    b["damage_class"] = cls.astype(object).where(cls.notna(), NO_DAMAGE)

    pmin = {z["name"]: z["p_min"] for z in zones}
    pmax = {z["name"]: z["p_max"] for z in zones}
    b["damage_pct_min"] = b["damage_class"].map(pmin).fillna(0.0)
    b["damage_pct_max"] = b["damage_class"].map(pmax).fillna(0.0)
    b["damage_pct_mid"] = (b["damage_pct_min"] + b["damage_pct_max"]) / 2
    for k in ("min", "max", "mid"):
        b[f"damage_area_{k}_m2"] = (b["area_m2"] * b[f"damage_pct_{k}"] / 100).round(1)
    b["damaged_zone"] = b["damage_class"] != NO_DAMAGE
    return b


def summarize_damage(b, zones=ZONES):
    order = [z["name"] for z in zones] + [NO_DAMAGE]
    g = b.groupby("damage_class", observed=False)
    t = pd.DataFrame({
        "будівель": g.size(),
        "площа_м2": g["area_m2"].sum().round(0),
        "збиток_мін_м2": g["damage_area_min_m2"].sum().round(0),
        "збиток_сер_м2": g["damage_area_mid_m2"].sum().round(0),
        "збиток_макс_м2": g["damage_area_max_m2"].sum().round(0),
        "екв_будівель_сер": (g["damage_pct_mid"].sum() / 100).round(1),
    }).reindex(order).fillna(0)
    t["частка_будівель_%"] = (t["будівель"] / t["будівель"].sum() * 100).round(1)
    return t

